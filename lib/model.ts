// The token radar's model: one sealed snapshot in, one ranked board out.
//
// The board ranks every pre-token protocol the house's own exclusion rule keeps: the
// 40 on the watchlist plus every other rankable protocol below the floor. A protocol is
// pre-token when its record carries no token (no market cap, no CoinGecko id, no symbol),
// and it is rankable when it is not a wrapped, staked or bridged product of a token that
// trades: no Bridge, Canonical Bridge, Liquid Staking, Liquid Restaking, Restaked BTC or
// CEX category, no version marker in its name, no whole word wrapped, staked or staking,
// and no exchange's name at the start. Live-token protocols are kept apart and shown as
// the market's own values, never mixed into the ranked board.
//
// Implied value is a comparable-multiple valuation, from the snapshot's own figures:
//
//   multiple   = the median mcap/TVL of the live-token protocols in the same category,
//                when at least three of them trade; otherwise the median across all 133
//                live-token protocols. The comparables are named in the board's model block.
//   base       = tvl_usd x multiple
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth    = 1 + 0.05 x min(chains - 1, 4)            (more chains, more reach)
//   implied    = max(1, round(base x growthMult x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row, and the
// dashboard shows the working for each one — its comparable set, its multiple and each
// multiplier — so a reader can check the number instead of trusting it.

